import React from 'react';
import { X, Thermometer, MapPin } from 'lucide-react';
import { GridCell, LayerType, MapGridResponse } from '../../types/api';
import { getTemperatureHex } from '../../utils/colorScale';

interface CellInspectorProps {
  cell: GridCell | null;
  layer: LayerType;
  gridData: MapGridResponse | null;
  onClose: () => void;
}

export const CellInspector: React.FC<CellInspectorProps> = ({
  cell,
  layer,
  gridData,
  onClose,
}) => {
  if (!cell) return null;

  const color = cell.value !== null ? getTemperatureHex(cell.value) : '#8b949e';

  const getSourceDetails = () => {
    if (layer === 'historical') {
      return {
        name: 'ERA5-Land Hourly Reanalysis',
        version: 'Copernicus C3S (v1)',
      };
    }
    return {
      name: gridData?.model_id || 'HeatSense ML Regressor',
      version: gridData?.model_version || 'v1',
    };
  };

  const source = getSourceDetails();

  return (
    <div className="inspector-card">
      <div className="inspector-header">
        <div className="inspector-title-row">
          <MapPin size={16} className="inspector-pin" />
          <span className="inspector-cell-id">{cell.id}</span>
        </div>
        <button className="inspector-close" onClick={onClose} title="Close Inspector">
          <X size={16} />
        </button>
      </div>

      <div className="inspector-body">
        <div className="inspector-temp-row">
          <div className="temp-display" style={{ color }}>
            <Thermometer size={28} />
            <span className="temp-number">{cell.value !== null ? `${cell.value}°C` : 'No Data'}</span>
          </div>
          <div className="layer-tag">
            {layer === 'historical' ? 'Observed' : layer === 'forecast24' ? '+24h Forecast' : '+48h Forecast'}
          </div>
        </div>

        <div className="inspector-grid-info">
          <div className="info-item">
            <span className="info-label">Coordinates</span>
            <span className="info-value">{cell.latitude.toFixed(2)}°N, {cell.longitude.toFixed(2)}°E</span>
          </div>
          <div className="info-item">
            <span className="info-label">Grid Spacing</span>
            <span className="info-value">~9 km (0.1°)</span>
          </div>
          <div className="info-item">
            <span className="info-label">Model / Source</span>
            <span className="info-value">{source.name}</span>
          </div>
          <div className="info-item">
            <span className="info-label">Version</span>
            <span className="info-value">{source.version}</span>
          </div>
        </div>

        <div className="inspector-disclaimer">
          Point temperature estimate generated by HeatSense models on 0.1° grid. Not street-level or official IMD warning.
        </div>
      </div>
    </div>
  );
};
